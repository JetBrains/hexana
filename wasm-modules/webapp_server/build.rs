use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let crate_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));

    let dist_env = env::var("HEXANA_WEBAPP_DIST").ok();
    let dist_dir: PathBuf = match &dist_env {
        Some(s) => PathBuf::from(s),
        None => crate_dir.join("../../webapp/build/dist/js/productionExecutable"),
    };

    println!("cargo:rerun-if-env-changed=HEXANA_WEBAPP_DIST");
    println!("cargo:rerun-if-changed={}", dist_dir.display());

    // Allowlisted root files (exact names).
    let root_allowlist: &[&str] = &[
        "index.html",
        "robots.txt",
        "boot.js",
        "webapp.js",
        "theme.css",
        "editor.css",
        "wasmprinter_wrapper.wasm",
    ];

    // Map from web path (e.g. "/webapp.js") -> (filesystem path, mime type)
    let mut assets: BTreeMap<String, (PathBuf, &'static str)> = BTreeMap::new();

    for name in root_allowlist {
        let p = dist_dir.join(name);
        if p.exists() {
            let mime = mime_for(name);
            assets.insert(format!("/{name}"), (p.clone(), mime));
            println!("cargo:rerun-if-changed={}", p.display());
        }
    }

    // Everything under composeResources/ recursively.
    let compose_dir = dist_dir.join("composeResources");
    if compose_dir.exists() {
        collect_dir(&compose_dir, &compose_dir, &mut assets);
        println!("cargo:rerun-if-changed={}", compose_dir.display());
    }

    // Emit the generated source.
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let out = out_dir.join("assets.rs");

    let mut src = String::from(
        "// Auto-generated by build.rs — do not edit.\n\
         pub struct Asset { pub data: &'static [u8], pub mime: &'static str }\n\
         pub fn find_asset(path: &str) -> Option<Asset> {\n\
             match path {\n",
    );

    for (web_path, (fs_path, mime)) in &assets {
        let fs_str = fs_path.to_str().unwrap().replace('\\', "/");
        src.push_str(&format!(
            "        {web_path:?} => Some(Asset {{ data: include_bytes!({fs_str:?}), mime: {mime:?} }}),\n"
        ));
    }

    src.push_str(
        "        _ => None,\n\
             }\n\
         }\n",
    );

    fs::write(&out, src).unwrap();
}

fn collect_dir(
    base: &Path,
    dir: &Path,
    assets: &mut BTreeMap<String, (PathBuf, &'static str)>,
) {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let p = entry.path();
        if p.is_dir() {
            collect_dir(base, &p, assets);
        } else if p.is_file() {
            let rel = p.strip_prefix(base).unwrap();
            let web_path = format!(
                "/composeResources/{}",
                rel.to_str().unwrap().replace('\\', "/")
            );
            let name = p.file_name().unwrap().to_str().unwrap();
            let mime = mime_for(name);
            println!("cargo:rerun-if-changed={}", p.display());
            assets.insert(web_path, (p, mime));
        }
    }
}

fn mime_for(name: &str) -> &'static str {
    if name.ends_with(".html") {
        "text/html; charset=utf-8"
    } else if name.ends_with(".txt") {
        "text/plain; charset=utf-8"
    } else if name.ends_with(".js") {
        "text/javascript"
    } else if name.ends_with(".css") {
        "text/css"
    } else if name.ends_with(".wasm") {
        "application/wasm"
    } else if name.ends_with(".json") {
        "application/json"
    } else if name.ends_with(".woff2") {
        "font/woff2"
    } else if name.ends_with(".woff") {
        "font/woff"
    } else if name.ends_with(".ttf") {
        "font/ttf"
    } else if name.ends_with(".svg") {
        "image/svg+xml"
    } else if name.ends_with(".png") {
        "image/png"
    } else {
        "application/octet-stream"
    }
}
