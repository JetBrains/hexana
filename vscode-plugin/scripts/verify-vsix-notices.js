#!/usr/bin/env node
// Verifies that a built VSIX ships its third-party notices:
//  - extension/THIRD-PARTY-NOTICES.md exists, is non-empty and names the runtime npm dependencies of the extension
//    host plus the posthog-node bundle input;
//  - every `*.js.LICENSE.txt` emitted by the webpack bundles is packaged next to its bundle (the extension must not
//    drop them through .vscodeignore).
// Usage: node scripts/verify-vsix-notices.js <path-to.vsix>

const fs = require("fs");
const path = require("path");
const AdmZip = require("adm-zip");

function fail(message) {
    console.error(`VSIX third-party notices check failed: ${message}`);
    process.exit(1);
}

const vsixPath = process.argv[2];
if (!vsixPath || !fs.existsSync(vsixPath)) {
    fail(`usage: verify-vsix-notices.js <path-to.vsix> (got ${vsixPath})`);
}

const packageRoot = path.resolve(__dirname, "..");
const zip = new AdmZip(vsixPath);
const entries = new Map(zip.getEntries().map((entry) => [entry.entryName, entry]));

const notices = entries.get("extension/THIRD-PARTY-NOTICES.md");
if (!notices) {
    fail("extension/THIRD-PARTY-NOTICES.md is missing from the VSIX");
}
const noticesText = notices.getData().toString("utf8");
if (noticesText.length < 1000) {
    fail("extension/THIRD-PARTY-NOTICES.md is suspiciously short");
}

const generated = path.join(packageRoot, "THIRD-PARTY-NOTICES.md");
if (!fs.existsSync(generated) || fs.readFileSync(generated, "utf8") !== noticesText) {
    fail("extension/THIRD-PARTY-NOTICES.md differs from the notices generated by :vscode-plugin:generateThirdPartyNotices");
}

const dependencies = Object.keys(require(path.join(packageRoot, "package.json")).dependencies || {});
for (const dependency of dependencies) {
    if (!new RegExp(`^### \`${dependency.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}@`, "m").test(noticesText)) {
        fail(`runtime npm dependency ${dependency} is not listed in THIRD-PARTY-NOTICES.md`);
    }
}
for (const required of ["posthog-node@", "cargo:wasmprinter@", "org.jetbrains.kotlin:kotlin-stdlib-js:"]) {
    if (!noticesText.includes(`\`${required}`)) {
        fail(`THIRD-PARTY-NOTICES.md does not list ${required}`);
    }
}

function licenseExtracts(directory) {
    if (!fs.existsSync(directory)) {
        return [];
    }
    return fs.readdirSync(directory).filter((name) => name.endsWith(".js.LICENSE.txt")).map((name) => path.join(directory, name));
}

const bundleDirectories = [
    "extension-lib/build/kotlin-webpack/js/productionExecutable",
    "webview/build/kotlin-webpack/js/productionExecutable",
];
for (const directory of bundleDirectories) {
    for (const extract of licenseExtracts(path.join(packageRoot, directory))) {
        const packaged = `extension/${path.relative(packageRoot, extract).split(path.sep).join("/")}`;
        if (!entries.has(packaged)) {
            fail(`${packaged} is missing from the VSIX`);
        }
    }
}

console.log(`VSIX third-party notices OK: ${path.basename(vsixPath)}`);
