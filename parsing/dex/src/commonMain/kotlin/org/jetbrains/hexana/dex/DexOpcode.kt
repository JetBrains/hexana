package org.jetbrains.hexana.dex

/**
 * Dalvik instruction format, as defined by the
 * [instruction formats reference](https://source.android.com/docs/core/runtime/instruction-formats).
 *
 * [id] is the canonical format name (`"22c"`), and [codeUnits] its fixed size in
 * 16-bit code units — the first digit of the name. The three payload
 * pseudo-instructions ([DexPayload]) are the only variable-length encodings; they
 * hide behind opcode `0x00` and are sized by [DexBytecodeDecoder], not by this enum.
 */
enum class DexFormat(val id: String, val codeUnits: Int) {
    F10T("10t", 1),
    F10X("10x", 1),
    F11N("11n", 1),
    F11X("11x", 1),
    F12X("12x", 1),
    F20T("20t", 2),
    F21C("21c", 2),
    F21H("21h", 2),
    F21S("21s", 2),
    F21T("21t", 2),
    F22B("22b", 2),
    F22C("22c", 2),
    F22S("22s", 2),
    F22T("22t", 2),
    F22X("22x", 2),
    F23X("23x", 2),
    F30T("30t", 3),
    F31C("31c", 3),
    F31I("31i", 3),
    F31T("31t", 3),
    F32X("32x", 3),
    F35C("35c", 3),
    F3RC("3rc", 3),
    F45CC("45cc", 4),
    F4RCC("4rcc", 4),
    F51L("51l", 5),
}

/**
 * What an instruction's `BBBB` (or `HHHH`) index refers to. Mirrors ART's
 * `kIndex*` classification; [UNKNOWN] marks the opcodes the format reserves as
 * unused, which never appear in a valid DEX file.
 */
enum class DexIndexKind {
    NONE,
    UNKNOWN,
    STRING,
    TYPE,
    FIELD,
    METHOD,
    METHOD_AND_PROTO,
    CALL_SITE,
    METHOD_HANDLE,
    PROTO,
}

