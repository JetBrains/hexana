package org.jetbrains.hexana.mcp

import org.jetbrains.hexana.wasm.opcodes.MemArg
import org.jetbrains.hexana.wasm.opcodes.OpCode
import org.jetbrains.hexana.wasm.opcodes.OpCodes
import org.jetbrains.hexana.wasm.sections.UnparsedOpCode

fun List<OpCode<*>>.wat(): String {
    return this.joinToString("\n") { it.watString() }
}

internal fun OpCode<*>.watString(): CharSequence {
    return when (this) {
        is OpCodes.Flow.Terminal -> "terminal"
        is OpCodes.Flow.Return -> "return"
        is OpCodes.Flow.ReturnCall -> "return_call"
        is OpCodes.Flow.Drop -> "drop"
        is OpCodes.Flow.Select -> "select"
        is OpCodes.Flow.Unreachable -> "unreachable"
        is OpCodes.Flow.Nop -> "nop"
        is OpCodes.Flow.Call -> "call ${value}"
        is OpCodes.Flow.CallIndirect -> "call_indirect ${value}"
        is OpCodes.Flow.Br -> "br $value"
        is OpCodes.Flow.BrIf -> "br_if $value"
        is OpCodes.Flow.BrTable -> "br_table (${value.joinToString(", ")})"
        is OpCodes.Flow.Loop -> "loop{\n${value.wat()}\n}"
        is OpCodes.Flow.If -> "if{\n${value.wat()}\n}"
        is OpCodes.Flow.Else -> "else{\n${value.wat()}\n}"
        is OpCodes.Local.Get -> "local.get $value"
        is OpCodes.Local.Set -> "local.set $value"
        is OpCodes.Local.Tee -> "local.tee $value"
        is OpCodes.Global.Get -> "global.get $value"
        is OpCodes.Global.Set -> "global.set $value"
        /* i32 */
        is OpCodes.I32.Load -> "i32.load ${value.watString()}"
        is OpCodes.I32.Load8_S -> "i32.load8_s ${value.watString()}"
        is OpCodes.I32.Load8_U -> "i32.load8_u ${value.watString()}"
        is OpCodes.I32.Load16_U -> "i32.load16_u ${value.watString()}"
        is OpCodes.I32.Store -> "i32.store ${value.watString()}"
        is OpCodes.I32.Store8 -> "i32.store8 ${value.watString()}"
        is OpCodes.I32.Store16 -> "i32.store16 ${value.watString()}"
        is OpCodes.I32.Const -> "i32.const $value"
        is OpCodes.I32.Shl -> "i32.shl"
        is OpCodes.I32.PopCnt -> "i32.popcnt"
        is OpCodes.I32.And -> "i32.and"
        is OpCodes.I32.Or -> "i32.or"
        is OpCodes.I32.Xor -> "i32.xor"
        is OpCodes.I32.Add -> "i32.add"
        is OpCodes.I32.Sub -> "i32.sub"
        is OpCodes.I32.Mul -> "i32.mul"
        is OpCodes.I32.Rotl -> "i32.rotl"
        is OpCodes.I32.Rotr -> "i32.rotr"
        is OpCodes.I32.Clz -> "i32.clz"
        is OpCodes.I32.Ctz -> "i32.ctz"
        is OpCodes.I32.Eqz -> "i32.eqz"
        is OpCodes.I32.Eq -> "i32.eq"
        is OpCodes.I32.Ne -> "i32.ne"
        is OpCodes.I32.LTS -> "i32.lt_s"
        is OpCodes.I32.LTU -> "i32.lt_u"
        is OpCodes.I32.LES -> "i32.le_s"
        is OpCodes.I32.LEU -> "i32.le_u"
        is OpCodes.I32.GTS -> "i32.gt_s"
        is OpCodes.I32.GTU -> "i32.gt_u"
        is OpCodes.I32.GES -> "i32.ge_s"
        is OpCodes.I32.GEU -> "i32.ge_u"
        is OpCodes.I32.RemS -> "i32.rem_s"
        is OpCodes.I32.RemU -> "i32.rem_u"
        is OpCodes.I32.WrapI64 -> "i32.wrap_i64"
        is OpCodes.I32.Extend16S -> "i32.extend16_s"
        is OpCodes.I32.ReinterpretF32 -> "i32.reinterpret_f32"
        is OpCodes.I32.TruncF32S -> "i32.trunc_f32_s"
        is OpCodes.I32.TruncF32U -> "i32.trunc_f32_u"
        is OpCodes.I32.TruncF64S -> "i32.trunc_f64_s"
        is OpCodes.I32.TruncF64U -> "i32.trunc_f64_u"
        is OpCodes.I32.DivU -> "i32.div_u"
        is OpCodes.I32.DivS -> "i32.div_s"
        is OpCodes.I32.ShrU -> "i32.shr_u"
        is OpCodes.I32.ShrS -> "i32.shr_s"
        /* i64 */
        is OpCodes.I64.Load -> "i64.load ${value.watString()}"
        is OpCodes.I64.Load8_S -> "i64.load8_s ${value.watString()}"
        is OpCodes.I64.Load8_U -> "i64.load8_u ${value.watString()}"
        is OpCodes.I64.Load16_U -> "i64.load16_u ${value.watString()}"
        is OpCodes.I64.Store -> "i64.store ${value.watString()}"
        is OpCodes.I64.Store8 -> "i64.store8 ${value.watString()}"
        is OpCodes.I64.Store16 -> "i64.store16 ${value.watString()}"
        is OpCodes.I64.Const -> "i64.const $value"
        is OpCodes.I64.Shl -> "i64.shl"
        is OpCodes.I64.PopCnt -> "i64.popcnt"
        is OpCodes.I64.And -> "i64.and"
        is OpCodes.I64.Or -> "i64.or"
        is OpCodes.I64.Xor -> "i64.xor"
        is OpCodes.I64.Add -> "i64.add"
        is OpCodes.I64.Sub -> "i64.sub"
        is OpCodes.I64.Mul -> "i64.mul"
        is OpCodes.I64.RotL -> "i64.rotl"
        is OpCodes.I64.RotR -> "i64.rotr"
        is OpCodes.I64.Extend_I32_S -> "i64.extend_i32_s"
        is OpCodes.I64.Extend_I32_U -> "i64.extend_i32_u"
        is OpCodes.I64.Clz -> "i64.clz"
        is OpCodes.I64.Ctz -> "i64.ctz"
        is OpCodes.I64.Eqz -> "i64.eqz"
        is OpCodes.I64.LTS -> "i64.lt_s"
        is OpCodes.I64.LTU -> "i64.lt_u"
        is OpCodes.I64.LES -> "i64.le_s"
        is OpCodes.I64.LEU -> "i64.le_u"
        is OpCodes.I64.GTS -> "i64.gt_s"
        is OpCodes.I64.GTU -> "i64.gt_u"
        is OpCodes.I64.GES -> "i64.ge_s"
        is OpCodes.I64.GEU -> "i64.ge_u"
        is OpCodes.I64.RemS -> "i64.rem_s"
        is OpCodes.I64.RemU -> "i64.rem_u"
        is OpCodes.I64.TruncF32S -> "i64.trunc_f32_s"
        is OpCodes.I64.TruncF32U -> "i64.trunc_f32_u"
        is OpCodes.I64.TruncF64S -> "i64.trunc_f64_s"
        is OpCodes.I64.TruncF64U -> "i64.trunc_f64_u"
        is OpCodes.I64.ReinterpretF64 -> "i64.reinterpret_f64"
        is OpCodes.I64.DivU -> "i64.div_u"
        is OpCodes.I64.DivS -> "i64.div_s"
        is OpCodes.I64.ShrU -> "i64.shr_u"
        is OpCodes.I64.ShrS -> "i64.shr_s"
        /* f32 */
        is OpCodes.F32.Const -> "f32.const $value"
        is OpCodes.F32.Nearest -> "f32.nearest"
        is OpCodes.F32.NE -> "f32.ne"
        is OpCodes.F32.LE -> "f32.le"
        is OpCodes.F32.Ceil -> "f32.ceil"
        is OpCodes.F32.Floor -> "f32.floor"
        is OpCodes.F32.Sub -> "f32.sub"
        is OpCodes.F32.Mul -> "f32.mul"
        is OpCodes.F32.Trunc -> "f32.trunc"
        is OpCodes.F32.CopySign -> "f32.copysign"
        is OpCodes.F32.Load -> "f32.load ${value.watString()}"
        is OpCodes.F32.Store -> "f32.store ${value.watString()}"
        is OpCodes.F32.Sqrt -> "f32.sqrt"
        is OpCodes.F32.Add -> "f32.add"
        is OpCodes.F32.Div -> "f32.div"
        is OpCodes.F32.Min -> "f32.min"
        is OpCodes.F32.Max -> "f32.max"
        is OpCodes.F32.DemoteF64 -> "f32.demote_f64"
        is OpCodes.F32.ReinterpretI32 -> "f32.reinterpret_i32"
        is OpCodes.F32.Neg -> "f32.neg"
        is OpCodes.F32.ConvertI32S -> "f32.convert_i32_s"
        is OpCodes.F32.ConvertI32U -> "f32.convert_i32_u"
        is OpCodes.F32.ConvertI64S -> "f32.convert_i64_s"
        is OpCodes.F32.ConvertI64U -> "f32.convert_i64_u"
        is OpCodes.F32.EQ -> "f32.eq"
        is OpCodes.F32.GE -> "f32.ge"
        is OpCodes.F32.GT -> "f32.gt"
        is OpCodes.F32.LT -> "f32.lt"
        is OpCodes.F32.Abs -> "f32.abs"
        /* f64 */
        is OpCodes.F64.Const -> "f64.const $value"
        is OpCodes.F64.Nearest -> "f64.nearest"
        is OpCodes.F64.NE -> "f64.ne"
        is OpCodes.F64.LE -> "f64.le"
        is OpCodes.F64.Ceil -> "f64.ceil"
        is OpCodes.F64.Floor -> "f64.floor"
        is OpCodes.F64.Sub -> "f64.sub"
        is OpCodes.F64.Mul -> "f64.mul"
        is OpCodes.F64.Trunc -> "f64.trunc"
        is OpCodes.F64.Copysign -> "f64.copysign"
        is OpCodes.F64.Sqrt -> "f64.sqrt"
        is OpCodes.F64.Add -> "f64.add"
        is OpCodes.F64.Div -> "f64.div"
        is OpCodes.F64.Min -> "f64.min"
        is OpCodes.F64.Max -> "f64.max"
        is OpCodes.F64.PromoteF32 -> "f64.promote_f32"
        is OpCodes.F64.ReinterpretI64 -> "f64.reinterpret_i64"
        is OpCodes.F64.Neg -> "f64.neg"
        is OpCodes.F64.ConvertI32S -> "f64.convert_i32_s"
        is OpCodes.F64.ConvertI32U -> "f64.convert_i32_u"
        is OpCodes.F64.ConvertI64S -> "f64.convert_i64_s"
        is OpCodes.F64.ConvertI64U -> "f64.convert_i64_u"
        is OpCodes.F64.EQ -> "f64.eq"
        is OpCodes.F64.GE -> "f64.ge"
        is OpCodes.F64.GT -> "f64.gt"
        is OpCodes.F64.LT -> "f64.lt"
        is OpCodes.F64.Abs -> "f64.abs"
        is UnparsedOpCode -> "unparsed block: ${value.joinToString { "0x${it.toHexString()}" }}"
        else -> toString()
    }
}

private fun MemArg.watString() = "offset=$offset align=$align"
