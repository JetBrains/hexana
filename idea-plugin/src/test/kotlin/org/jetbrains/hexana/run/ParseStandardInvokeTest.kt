package org.jetbrains.hexana.run

import com.intellij.testFramework.UsefulTestCase

class ParseStandardInvokeTest : UsefulTestCase() {

    fun testNoInvoke() {
        assertNull(parseStandardInvoke(""))
        assertNull(parseStandardInvoke("--some-flag"))
        assertNull(parseStandardInvoke("-W unknown-imports-default"))
    }

    fun testSimpleInvoke() {
        val result = parseStandardInvoke("--invoke add")!!
        assertEquals("add", result.exportName)
        assertEquals("", result.inlineArgs)
        assertEquals("", result.remainingOptions)
    }

    fun testInvokeWithRemainingOptions() {
        val result = parseStandardInvoke("-W unknown-imports-default --invoke add")!!
        assertEquals("add", result.exportName)
        assertEquals("", result.inlineArgs)
        assertEquals("-W unknown-imports-default", result.remainingOptions)
    }

    fun testInvokeWithTrailingOptions() {
        val result = parseStandardInvoke("--invoke add --dir /tmp")!!
        assertEquals("add", result.exportName)
        assertEquals("", result.inlineArgs)
        assertEquals("--dir /tmp", result.remainingOptions)
    }

    fun testQuotedInvokeWithArgs() {
        val result = parseStandardInvoke("""--invoke "myFunc(1, 2)"""")!!
        assertEquals("myFunc", result.exportName)
        assertEquals("1, 2", result.inlineArgs)
        assertEquals("", result.remainingOptions)
    }

    fun testQuotedInvokeWithArgsAndRemainingOptions() {
        val result = parseStandardInvoke("""-W unknown-imports-default --invoke "myFunc(1, 2)"""")!!
        assertEquals("myFunc", result.exportName)
        assertEquals("1, 2", result.inlineArgs)
        assertEquals("-W unknown-imports-default", result.remainingOptions)
    }

    fun testQuotedInvokeNoArgs() {
        val result = parseStandardInvoke("""--invoke "myFunc()"""")!!
        assertEquals("myFunc", result.exportName)
        assertEquals("", result.inlineArgs)
        assertEquals("", result.remainingOptions)
    }

    fun testCoreWasmPatternFromRunExportedFunction() {
        // Matches the pattern generated by WasmPanelExports.runExportedFunction
        val result = parseStandardInvoke("--invoke add")!!
        assertEquals("add", result.exportName)
        assertEquals("", result.inlineArgs)
        assertEquals("", result.remainingOptions)
    }

    fun testComponentPatternFromRunComponentExportedFunction() {
        // Matches the pattern generated by WasmComponentPanelExports.runComponentExportedFunction
        val result = parseStandardInvoke("""--invoke "myFunc(42, hello)"""")!!
        assertEquals("myFunc", result.exportName)
        assertEquals("42, hello", result.inlineArgs)
        assertEquals("", result.remainingOptions)
    }

    fun testWhitespace() {
        val result = parseStandardInvoke("  --invoke   add  ")!!
        assertEquals("add", result.exportName)
        assertEquals("", result.inlineArgs)
        assertEquals("", result.remainingOptions)
    }

    fun testRoundTripCoreWasm() {
        // Simulate: wasmtime config has --invoke add, program args = "1 2"
        // Switch to graalwasm: exportName = "add", programArgs stays "1 2"
        // Switch back to wasmtime: should reconstruct --invoke add
        val parsed = parseStandardInvoke("--invoke add")!!
        assertEquals("add", parsed.exportName)
        assertEquals("", parsed.inlineArgs)
    }

    fun testRoundTripComponent() {
        // Simulate: wasmtime config has --invoke "myFunc(1, 2)", program args = ""
        // Switch to graalwasm: exportName = "myFunc", programArgs = "1, 2"
        // Switch back to wasmtime: should reconstruct --invoke "myFunc(1, 2)"
        val parsed = parseStandardInvoke("""--invoke "myFunc(1, 2)"""")!!
        assertEquals("myFunc", parsed.exportName)
        assertEquals("1, 2", parsed.inlineArgs)
    }
}
