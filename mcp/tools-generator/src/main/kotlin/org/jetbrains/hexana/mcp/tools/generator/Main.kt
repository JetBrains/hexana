package org.jetbrains.hexana.mcp.tools.generator

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterSpec
import org.jetbrains.hexana.mcp.tools.ClassSpec
import org.jetbrains.hexana.mcp.tools.HexanaTools
import org.jetbrains.hexana.mcp.tools.ToolSpec
import java.nio.file.Files
import java.nio.file.Path
import kotlin.system.exitProcess

private const val GENERATED_PACKAGE = "org.jetbrains.hexana.mcp.server.gen"
private const val SERVER_PACKAGE = "org.jetbrains.hexana.mcp.server"
private val SERVER_CLASS = ClassName("io.modelcontextprotocol.kotlin.sdk.server", "Server")
private val TOOL_CLASS = ClassName("io.modelcontextprotocol.kotlin.sdk.types", "Tool")
private val CALL_TOOL_REQUEST = ClassName("io.modelcontextprotocol.kotlin.sdk.types", "CallToolRequest")
private val TOOL_HANDLERS = ClassName(SERVER_PACKAGE, "HexanaToolHandlers")

fun main(args: Array<String>) {
    val outputRoot = args.firstOrNull()?.let(Path::of) ?: run {
        System.err.println("Usage: standalone-toolset-generator <output-root>")
        exitProcess(1)
    }

    try {
        Files.createDirectories(outputRoot)
    } catch (error: Exception) {
        System.err.println("Failed to create output directory '$outputRoot': ${error.message}")
        exitProcess(1)
    }
    val fileSpec = buildDispatcherFile(HexanaTools)
    fileSpec.writeTo(outputRoot)
    println("Wrote ${fileSpec.packageName}.${fileSpec.name} to $outputRoot")
}

private fun buildDispatcherFile(tools: List<ToolSpec>): FileSpec {
    val registerFun = FunSpec.builder("registerHexanaTools")
        .receiver(SERVER_CLASS)
        .addParameter(ParameterSpec.builder("handlers", TOOL_HANDLERS).build())
        .addKdoc(
            "Registers all Hexana MCP tools on the receiver Server.\n\n" +
                "Generated by `:mcp:tools-generator`. Do not edit by hand.",
        )
        .apply {
            tools.forEach { spec ->
                addCode(renderAddToolCall(spec))
                addCode("\n")
            }
        }
        .build()

    return FileSpec.builder(GENERATED_PACKAGE, "HexanaToolDispatcherGenerated")
        .addFileComment("Generated by :mcp:tools-generator. Do not edit by hand.")
        .addFunction(registerFun)
        .build()
}

private fun renderAddToolCall(spec: ToolSpec): CodeBlock {
    val handlerMethod = spec.name.toCamelCase()
    val schema = schemaInvocation(spec.input)

    return CodeBlock.builder()
        .add(
            "addTool(tool = %T(\n  name = %S,\n  description = %S,\n  inputSchema = %L,\n))",
            TOOL_CLASS, spec.name, spec.summary, schema,
        )
        .beginControlFlow(" ")
        .addStatement("request: %T -> handlers.%N(request.arguments)", CALL_TOOL_REQUEST, handlerMethod)
        .endControlFlow()
        .build()
}

/**
 * Maps each input ClassSpec's `name` to the corresponding schema helper already
 * shipped with `mcp/server`. A new input shape must either reuse an existing
 * helper name or register a new one here + in `HexanaMcpServer.kt`.
 */
private fun schemaInvocation(input: ClassSpec): CodeBlock {
    val wasmInput = MemberName(SERVER_PACKAGE, "wasmInputToolSchema")
    val listFunctions = MemberName(SERVER_PACKAGE, "listFunctionsSchema")
    val pathAndIndices = MemberName(SERVER_PACKAGE, "pathAndIndicesSchema")
    val listExportedFunctions = MemberName(SERVER_PACKAGE, "listExportedFunctionsSchema")
    val listData = MemberName(SERVER_PACKAGE, "listDataSchema")
    val listDataSegments = MemberName(SERVER_PACKAGE, "listDataSegmentsSchema")

    val helper = when (input.name) {
        "WasmInput" -> wasmInput
        "ListFunctionsInput" -> listFunctions
        "FunctionsForIndicesInput",
        "GetGlobalsForIndicesInput",
        "GetMemoryForIndicesInput",
        "GetTypesForIndicesInput",
        "GetLocalsForFunctionsInput",
        "GetInstructionsForFunctionsInput" -> pathAndIndices
        "ListExportedFunctionsInput" -> listExportedFunctions
        "ListDataInput" -> listData
        "ListDataSegmentsInput" -> listDataSegments
        else -> error(
            "Input class '${input.name}' does not map to a known schema helper. " +
                "Add a mapping in `schemaInvocation` or register a new helper in mcp/server.",
        )
    }

    return if (helper.simpleName == "pathAndIndicesSchema") {
        val indicesDescription = input.fields
            .single { it.name == "indices" }
            .let { requireNotNull(it.describe) { "pathAndIndicesSchema handler requires a describe() on `indices`." } }
        CodeBlock.of("%M(%S)", helper, indicesDescription)
    } else {
        CodeBlock.of("%M()", helper)
    }
}

private fun String.toCamelCase(): String {
    // Input contract: strict snake_case tool names (lowercase, single underscores). The Dsl enforces
    // this via its validation; here we fail loudly if an odd shape slips through instead of silently
    // producing weird handler method names.
    require(isNotEmpty()) { "toCamelCase called on empty string" }
    val parts = split('_').filter { it.isNotEmpty() }
    require(parts.isNotEmpty()) { "tool name `$this` has no non-empty segments" }
    return parts.first() + parts.drop(1).joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }
}

