import kotlin.system.exitProcess

private const val IDEA_PACKAGE = "org.jetbrains.hexana.mcp"

private val MCP_TOOL = ClassName("com.intellij.mcpserver.annotations", "McpTool")
private val MCP_DESCRIPTION = ClassName("com.intellij.mcpserver.annotations", "McpDescription")
private val MCP_TOOLSET = ClassName("com.intellij.mcpserver", "McpToolset")
private val CONSTANTS = ClassName("com.intellij.mcpserver.toolsets", "Constants")

/**
 * Maps each generated-toolset method's return type to the package its data
 * class lives in under `mcp/core/model/`. Update when adding new tool outputs.
 */
private val RESULT_PACKAGE: Map<String, String> = mapOf(
    "SummarizeModuleResult" to "org.jetbrains.hexana.mcp.model.summary",
    "ListImportsResult" to "org.jetbrains.hexana.mcp.model.imports",
    "ListExportsResult" to "org.jetbrains.hexana.mcp.model.exports",
    "ListExportedFunctionsResult" to "org.jetbrains.hexana.mcp.model.exports",
    "ListGlobalsResult" to "org.jetbrains.hexana.mcp.model.globals",
    "ListMemoryResult" to "org.jetbrains.hexana.mcp.model.memory",
    "ListElementSegmentsResult" to "org.jetbrains.hexana.mcp.model.elements",
    "TypesResult" to "org.jetbrains.hexana.mcp.model.types",
    "FunctionsResult" to "org.jetbrains.hexana.mcp.model.functions",
    "GetInstructionsForFunctionsResult" to "org.jetbrains.hexana.mcp.model.functions",
    "GetLocalsForFunctionsResult" to "org.jetbrains.hexana.mcp.model.functions",
    "ListDataSectionsResult" to "org.jetbrains.hexana.mcp.model.data",
    "ListDataSegmentsResult" to "org.jetbrains.hexana.mcp.model.data",
)

fun main(args: Array<String>) {
    val outputRoot = args.firstOrNull()?.let(Path::of) ?: run {
        System.err.println("Usage: toolset-generator <output-root>")
        exitProcess(1)
    }
    Files.createDirectories(outputRoot)
    val fileSpec = buildToolsetFile(HexanaTools)
    fileSpec.writeTo(outputRoot)
    println("Wrote ${fileSpec.packageName}.${fileSpec.name} to $outputRoot")
}

private fun buildToolsetFile(tools: List<ToolSpec>): FileSpec {
    val clsBuilder = TypeSpec.classBuilder("HexanaToolset")
        .addSuperinterface(MCP_TOOLSET)
        .addKdoc("Generated by `:mcp:tools-generator`. Do not edit by hand.")
    tools.forEach { spec -> clsBuilder.addFunction(buildMethod(spec)) }
    return FileSpec.builder(IDEA_PACKAGE, "HexanaToolset")
        .addFileComment("Generated by :mcp:tools-generator. Do not edit by hand.")
        .addType(clsBuilder.build())
        .build()
}

private fun buildMethod(spec: ToolSpec): FunSpec {
    val pkg = RESULT_PACKAGE[spec.output.name]
        ?: error("No package mapping for result class '${spec.output.name}'. Add to RESULT_PACKAGE.")
    val returnType = ClassName(pkg, spec.output.name)
    val methodName = spec.name.toToolsetMethodName()
    val handlerSimpleName = spec.handlerFqn.substringAfterLast('.')

    val builder = FunSpec.builder(methodName)
        .addModifiers(KModifier.SUSPEND)
        .addAnnotation(AnnotationSpec.builder(MCP_TOOL).addMember("%S", spec.name).build())
        .addAnnotation(
            AnnotationSpec.builder(MCP_DESCRIPTION)
                .addMember(
                    "%S",
                    buildDescription(spec),
                )
                .build(),
        )
        .returns(returnType)

    addParameters(builder, spec)
    addBody(builder, spec, handlerSimpleName)
    return builder.build()
}

private fun buildDescription(spec: ToolSpec): String {
    val guidance = spec.guidance
    return if (guidance.isNullOrBlank()) {
        spec.summary
    } else {
        "${spec.summary}\n${guidance.trim()}"
    }
}

private fun addParameters(builder: FunSpec.Builder, spec: ToolSpec) {
    builder.addParameter(pathParameter())
    when (spec.input.name) {
        "WasmInput" -> Unit
        "ListFunctionsInput" -> {
            builder.addParameter(intWithDefault("offset", 0, fieldDescribe(spec.input, "offset")))
            builder.addParameter(intWithDefault("limit", 200, fieldDescribe(spec.input, "limit")))
        }
        "FunctionsForIndicesInput",
        "GetGlobalsForIndicesInput",
        "GetMemoryForIndicesInput",
        "GetTypesForIndicesInput",
        "GetLocalsForFunctionsInput",
        "GetInstructionsForFunctionsInput" ->
            builder.addParameter(intListParam("indices", fieldDescribe(spec.input, "indices")))
        "ListExportedFunctionsInput", "ListDataInput" ->
            builder.addParameter(mapParam("entriesRange", fieldDescribe(spec.input, "entriesRange")))
        "ListDataSegmentsInput" -> {
            builder.addParameter(mapParam("segmentRange", fieldDescribe(spec.input, "segmentRange")))
            builder.addParameter(
                boolWithDefault("includeExports", false, fieldDescribe(spec.input, "includeExports")),
            )
            builder.addParameter(
                boolWithDefault("includeGlobals", true, fieldDescribe(spec.input, "includeGlobals")),
            )
            builder.addParameter(nullableIntParam("minByteLength", fieldDescribe(spec.input, "minByteLength")))
        }
        else -> error("Unmapped input class '${spec.input.name}' in toolset generator.")
    }
}

private fun addBody(builder: FunSpec.Builder, spec: ToolSpec, handlerSimpleName: String) {
    val code = CodeBlock.builder()
    code.addStatement("val file = %M(path)", REQUIRE_WASM_FILE)
    when (spec.input.name) {
        "ListExportedFunctionsInput", "ListDataInput" ->
            code.addStatement("val range = %M(entriesRange, %S)", REQUIRE_CLOSED_RANGE, "entriesRange")
        "ListDataSegmentsInput" ->
            code.addStatement("val range = %M(segmentRange)", REQUIRE_HALF_OPEN_RANGE)
    }
    code.addStatement("val buffer = file.%M()", CONTENTS_TO_BUFFER)
    code.addStatement("val module = buffer.%M()", REQUIRE_PARSED_WASM_MODULE)

    val queryMember = MemberName(QUERY_PACKAGE, handlerSimpleName)
    val callArgs: String = when (spec.input.name) {
        "WasmInput" -> "(module)"
        "ListFunctionsInput" -> "(module, offset, limit)"
        "FunctionsForIndicesInput",
        "GetGlobalsForIndicesInput",
        "GetMemoryForIndicesInput",
        "GetTypesForIndicesInput",
        "GetLocalsForFunctionsInput",
        "GetInstructionsForFunctionsInput" -> "(module, indices)"
        "ListExportedFunctionsInput", "ListDataInput" -> "(module, range)"
        "ListDataSegmentsInput" -> "(module, range, includeExports, includeGlobals, minByteLength ?: 0)"
        else -> error("unreachable")
    }
    code.addStatement("return buffer.%M$callArgs", queryMember)
    builder.addCode(code.build())
}

// ---------- parameter helpers ----------

private fun pathParameter(): ParameterSpec =
    ParameterSpec.builder("path", String::class)
        .addAnnotation(
            AnnotationSpec.builder(MCP_DESCRIPTION)
                .addMember("%T.RELATIVE_PATH_IN_PROJECT_DESCRIPTION", CONSTANTS)
                .build(),
        )
        .build()

private fun intWithDefault(name: String, default: Int, describe: String): ParameterSpec =
    ParameterSpec.builder(name, Int::class)
        .addAnnotation(describeAnnotation(describe))
        .defaultValue("%L", default)
        .build()

private fun boolWithDefault(name: String, default: Boolean, describe: String): ParameterSpec =
    ParameterSpec.builder(name, Boolean::class)
        .addAnnotation(describeAnnotation(describe))
        .defaultValue("%L", default)
        .build()

private fun nullableIntParam(name: String, describe: String): ParameterSpec =
    ParameterSpec.builder(name, Int::class.asClassName().copy(nullable = true))
        .addAnnotation(describeAnnotation(describe))
        .defaultValue("null")
        .build()

private fun intListParam(name: String, describe: String): ParameterSpec =
    ParameterSpec.builder(
        name,
        List::class.asClassName().parameterizedBy(Int::class.asClassName()),
    )
        .addAnnotation(describeAnnotation(describe))
        .build()

private fun mapParam(name: String, describe: String): ParameterSpec =
    ParameterSpec.builder(
        name,
        Map::class.asClassName().parameterizedBy(String::class.asClassName(), Int::class.asClassName()),
    )
        .addAnnotation(describeAnnotation(describe))
        .build()

private fun describeAnnotation(text: String): AnnotationSpec =
    AnnotationSpec.builder(MCP_DESCRIPTION).addMember("%S", text).build()

private fun fieldDescribe(cls: ClassSpec, fieldName: String): String =
    cls.fields.single { it.name == fieldName }.describe
        ?: error("Field '$fieldName' on class '${cls.name}' must have a .describe().")

// Hexana-specific snake_case → camelCase; `get_instructions_for_functions` → `getInstructionsForFunctions`.
private fun String.toToolsetMethodName(): String {
    val parts = split('_')
    return parts.first() + parts.drop(1).joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }
}

private const val QUERY_PACKAGE = "org.jetbrains.hexana.mcp.query"

// Helpers resolved at generated-code compile time via the hand-written
// ToolsetHelpers.kt file shipped alongside the generated class.
private val REQUIRE_WASM_FILE = MemberName(IDEA_PACKAGE, "requireWasmFile")
private val REQUIRE_CLOSED_RANGE = MemberName(IDEA_PACKAGE, "requireClosedRange")
private val REQUIRE_HALF_OPEN_RANGE = MemberName(IDEA_PACKAGE, "requireHalfOpenSegmentRange")
private val CONTENTS_TO_BUFFER = MemberName(IDEA_PACKAGE, "contentsToCommonByteBuffer")
private val REQUIRE_PARSED_WASM_MODULE = MemberName(IDEA_PACKAGE, "requireParsedWasmModule")
