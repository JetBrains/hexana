fun main(args: Array<String>) {
    val outputRoot = args.firstOrNull()?.let(Path::of) ?: run {
        System.err.println("Usage: toolset-generator <output-root>")
        exitProcess(1)
    }
    Files.createDirectories(outputRoot)
    val fileSpec = buildToolsetFile(HexanaTools)
    fileSpec.writeTo(outputRoot)
    println("Wrote ${fileSpec.packageName}.${fileSpec.name} to $outputRoot")
}

private fun buildToolsetFile(tools: List<ToolSpec>): FileSpec {
    val cls = TypeSpec.classBuilder("HexanaToolset")
        .addSuperinterface(MCP_TOOLS_PROVIDER)
        .addKdoc("Generated by `:mcp:tools-generator`. Do not edit by hand.")
        .addFunction(buildGetToolsMethod(tools))
        .build()

    return FileSpec.builder(IDEA_PACKAGE, "HexanaToolset")
        .addFileComment("Generated by :mcp:tools-generator. Do not edit by hand.")
        .addImport(
            "kotlinx.serialization.json",
            "booleanOrNull",
            "int",
            "intOrNull",
            "jsonArray",
            "jsonObject",
            "jsonPrimitive",
        )
        .addType(cls)
        .addFunction(requireStringArgumentFunction())
        .addFunction(requireIntArgumentFunction())
        .addFunction(optionalStringArgumentFunction())
        .addFunction(optionalIntArgumentFunction())
        .addFunction(optionalBooleanArgumentFunction())
        .addFunction(requireStringListArgumentFunction())
        .addFunction(optionalStringListArgumentFunction())
        .addFunction(requireIntListArgumentFunction())
        .addFunction(requireIntMapArgumentFunction())
        .addFunction(hexanaToolCategoryFunction())
        .addFunction(hexanaToolDescriptorFunction())
        .build()
}

private fun buildGetToolsMethod(tools: List<ToolSpec>): FunSpec {
    val builder = FunSpec.builder("getTools")
        .addModifiers(KModifier.OVERRIDE)
        .returns(LIST.parameterizedBy(MCP_TOOL))

    val code = CodeBlock.builder()
    code.add("return listOf(\n")
    tools.forEachIndexed { index, spec ->
        code.add(buildToolObject(spec))
        if (index != tools.lastIndex) {
            code.add(",")
        }
        code.add("\n")
    }
    code.add(")\n")
    builder.addCode(code.build())
    return builder.build()
}

private fun buildToolObject(spec: ToolSpec): CodeBlock {
    return CodeBlock.builder()
        .add("object : %T {\n", MCP_TOOL)
        .indent()
        .add("override val descriptor: %T = hexanaToolDescriptor(\n", MCP_TOOL_DESCRIPTOR)
        .indent()
        .add("name = %S,\n", spec.name)
        .add("description = %S,\n", buildDescription(spec))
        .add("fullyQualifiedName = %S,\n", "$IDEA_PACKAGE.HexanaToolset.${spec.name.toToolsetMethodName()}")
        .add("inputSchema = %L,\n", buildIdeaInputSchema(spec))
        .add("outputSchema = %L,\n", buildToolSchema(spec.output))
        .unindent()
        .add(")\n")
        .add("override suspend fun call(args: %T): %T {\n", JSON_OBJECT, MCP_TOOL_CALL_RESULT)
        .indent()
        .add(buildToolBody(spec))
        .unindent()
        .add("}\n")
        .unindent()
        .add("}")
        .build()
}

private fun buildToolBody(spec: ToolSpec): CodeBlock {
    val code = CodeBlock.builder()
    code.addStatement("val path = args.requireStringArgument(%S)", "path")
    when (val pattern = spec.inputPattern) {
        ToolInputPattern.WasmOnly -> Unit
        ToolInputPattern.WasmPathLabel -> Unit
        ToolInputPattern.WasmWithBaseline ->
            code.addStatement("val baselinePath = args.requireStringArgument(%S)", "baselinePath")
        ToolInputPattern.WasmWithBinding ->
            code.addStatement("val bindingPath = args.requireStringArgument(%S)", "bindingPath")
        ToolInputPattern.WasmWithConfig ->
            code.addStatement("val configPath = args.requireStringArgument(%S)", "configPath")
        ToolInputPattern.FunctionPage -> {
            val offset = inputField(spec.input, "offset").defaultOrError<Int>()
            val limit = inputField(spec.input, "limit").defaultOrError<Int>()
            code.addStatement("val offset = args.optionalIntArgument(%S) ?: %L", "offset", offset)
            code.addStatement("val limit = args.optionalIntArgument(%S) ?: %L", "limit", limit)
        }
        ToolInputPattern.Funcidx ->
            code.addStatement("val funcidx = args.requireIntArgument(%S)", "funcidx")
        ToolInputPattern.FunctionNameSearch -> {
            val limit = inputField(spec.input, "limit").defaultOrError<Int>()
            code.addStatement("val query = args.requireStringArgument(%S)", "query")
            code.addStatement("val limit = args.optionalIntArgument(%S) ?: %L", "limit", limit)
        }
        ToolInputPattern.ExportNameSearch -> {
            val limit = inputField(spec.input, "limit").defaultOrError<Int>()
            code.addStatement("val query = args.requireStringListArgument(%S)", "query")
            code.addStatement("val limit = args.optionalIntArgument(%S) ?: %L", "limit", limit)
        }
        ToolInputPattern.Indices ->
            code.addStatement("val indices = args.requireIntListArgument(%S)", "indices")
        is ToolInputPattern.ClosedRange -> {
            code.addStatement("val %N = args.requireIntMapArgument(%S)", pattern.parameterName, pattern.parameterName)
            code.addStatement(
                "val range = %M(%N, %S)",
                REQUIRE_CLOSED_RANGE,
                pattern.parameterName,
                pattern.parameterName,
            )
        }
        ToolInputPattern.DataSegments -> {
            val includeExports = inputField(spec.input, "includeExports").defaultOrError<Boolean>()
            val includeGlobals = inputField(spec.input, "includeGlobals").defaultOrError<Boolean>()
            code.addStatement("val segmentRange = args.requireIntMapArgument(%S)", "segmentRange")
            code.addStatement("val includeExports = args.optionalBooleanArgument(%S) ?: %L", "includeExports", includeExports)
            code.addStatement("val includeGlobals = args.optionalBooleanArgument(%S) ?: %L", "includeGlobals", includeGlobals)
            code.addStatement("val minByteLength = args.optionalIntArgument(%S)", "minByteLength")
            code.addStatement("val range = %M(segmentRange)", REQUIRE_HALF_OPEN_RANGE)
        }
        ToolInputPattern.ArtifactQuery -> {
            val operation = inputField(spec.input, "operation").defaultOrError<String>()
            val limit = inputField(spec.input, "limit").defaultOrError<Int>()
            val detail = inputField(spec.input, "detail").defaultOrError<String>()
            val maxBytes = inputField(spec.input, "maxBytes").defaultOrError<Int>()
            code.addStatement("val operation = args.optionalStringArgument(%S) ?: %S", "operation", operation)
            code.addStatement("val entityTypes = args.optionalStringListArgument(%S)", "entityTypes")
            code.addStatement("val query = args.optionalStringListArgument(%S)", "query")
            code.addStatement("val baselinePath = args.optionalStringArgument(%S)", "baselinePath")
            code.addStatement("val bindingPath = args.optionalStringArgument(%S)", "bindingPath")
            code.addStatement("val configPath = args.optionalStringArgument(%S)", "configPath")
            code.addStatement("val startName = args.optionalStringArgument(%S)", "startName")
            code.addStatement("val startFuncidx = args.optionalIntArgument(%S)", "startFuncidx")
            code.addStatement("val relations = args.optionalStringListArgument(%S)", "relations")
            code.addStatement("val limit = args.optionalIntArgument(%S) ?: %L", "limit", limit)
            code.addStatement("val detail = args.optionalStringArgument(%S) ?: %S", "detail", detail)
            code.addStatement("val maxBytes = args.optionalIntArgument(%S) ?: %L", "maxBytes", maxBytes)
        }
        ToolInputPattern.PolicyWithBaselineAndLog -> {
            code.addStatement("val baselinePath = args.requireStringArgument(%S)", "baselinePath")
            code.addStatement("val policyPath = args.requireStringArgument(%S)", "policyPath")
            code.addStatement("val logPath = args.optionalStringArgument(%S)", "logPath")
        }
        ToolInputPattern.RuntimeCompatibility -> {
            code.addStatement("val runtime = args.requireStringArgument(%S)", "runtime")
            code.addStatement("val version = args.optionalStringArgument(%S)", "version")
        }
    }
    code.addStatement("val file = %M(path)", REQUIRE_WASM_FILE)
    code.addStatement("val provider = file.%M()", REQUIRE_CORE_WASM_BINARY_PROVIDER)

    val handlerMember = spec.handlerMemberName()
    if (spec.inputPattern == ToolInputPattern.ArtifactQuery) {
        code.addStatement(
            "val baselineProvider = baselinePath?.let { %M(it).%M() }",
            REQUIRE_WASM_FILE,
            REQUIRE_CORE_WASM_BINARY_PROVIDER,
        )
        code.addStatement(
            "val bindingText = bindingPath?.let { %M(it) }",
            REQUIRE_TEXT_FILE,
        )
        code.addStatement(
            "val configText = configPath?.let { %M(it) }",
            REQUIRE_TEXT_FILE,
        )
        code.addStatement(
            "val result = provider.%M(" +
                "baseline = baselineProvider, " +
                "bindingText = bindingText, " +
                "configText = configText, " +
                "operation = operation, " +
                "entityTypes = entityTypes.orEmpty(), " +
                "query = query.orEmpty(), " +
                "startName = startName, " +
                "startFuncidx = startFuncidx, " +
                "relations = relations.orEmpty(), " +
                "limit = limit, " +
                "detail = detail, " +
                "maxBytes = maxBytes, " +
                "pathLabel = path, " +
                "baselinePathLabel = baselinePath, " +
                "bindingPathLabel = bindingPath, " +
                "configPathLabel = configPath" +
                ")",
            handlerMember,
        )
    } else if (spec.inputPattern == ToolInputPattern.PolicyWithBaselineAndLog) {
        code.addStatement(
            "val baselineProvider = %M(baselinePath).%M()",
            REQUIRE_WASM_FILE,
            REQUIRE_CORE_WASM_BINARY_PROVIDER,
        )
        code.addStatement("val policyText = %M(policyPath)", REQUIRE_TEXT_FILE)
        code.addStatement("val logText = logPath?.let { %M(it) }", REQUIRE_TEXT_FILE)
        code.addStatement(
            "val result = provider.%M(baseline = baselineProvider, policyText = policyText, logText = logText)",
            handlerMember,
        )
    } else if (spec.inputPattern == ToolInputPattern.WasmWithBaseline) {
        code.addStatement(
            "val baselineProvider = %M(baselinePath).%M()",
            REQUIRE_WASM_FILE,
            REQUIRE_CORE_WASM_BINARY_PROVIDER,
        )
        code.addStatement(
            "val result = provider.%M(baseline = baselineProvider, pathLabel = path, baselinePathLabel = baselinePath)",
            handlerMember,
        )
    } else if (spec.inputPattern == ToolInputPattern.WasmWithBinding) {
        code.addStatement("val bindingText = %M(bindingPath)", REQUIRE_TEXT_FILE)
        code.addStatement(
            "val result = provider.%M(bindingText = bindingText, pathLabel = path, bindingPathLabel = bindingPath)",
            handlerMember,
        )
    } else if (spec.inputPattern == ToolInputPattern.WasmWithConfig) {
        code.addStatement("val configText = %M(configPath)", REQUIRE_TEXT_FILE)
        code.addStatement(
            "val result = provider.%M(configText = configText, pathLabel = path, configPathLabel = configPath)",
            handlerMember,
        )
    } else {
        val callArgs: String = when (spec.inputPattern) {
            ToolInputPattern.WasmOnly -> "()"
            ToolInputPattern.WasmPathLabel -> "(pathLabel = path)"
            ToolInputPattern.WasmWithBaseline -> error("Handled above")
            ToolInputPattern.WasmWithBinding -> error("Handled above")
            ToolInputPattern.WasmWithConfig -> error("Handled above")
            ToolInputPattern.FunctionPage -> "(offset, limit)"
            ToolInputPattern.Funcidx -> "(funcidx)"
            ToolInputPattern.FunctionNameSearch -> "(query, limit)"
            ToolInputPattern.ExportNameSearch -> "(query, limit)"
            ToolInputPattern.Indices -> "(indices)"
            is ToolInputPattern.ClosedRange -> "(range)"
            ToolInputPattern.DataSegments -> "(range, includeExports, includeGlobals, minByteLength ?: 0)"
            ToolInputPattern.ArtifactQuery -> error("Handled above")
            ToolInputPattern.PolicyWithBaselineAndLog -> error("Handled above")
            ToolInputPattern.RuntimeCompatibility -> "(runtime, version)"
        }
        code.addStatement("val result = provider.%M$callArgs", handlerMember)
    }
    code.addStatement("val text = %M(result)", ENCODE_HEXANA_JSON)
    code.addStatement("val structuredContent = %M(result).jsonObject", ENCODE_HEXANA_JSON_ELEMENT)
    code.addStatement("return %T.text(text, structuredContent)", MCP_TOOL_CALL_RESULT)
    return code.build()
}

private fun buildDescription(spec: ToolSpec): String {
    val guidance = spec.guidance
    return if (guidance.isNullOrBlank()) {
        spec.summary
    } else {
        "${spec.summary}\n${guidance.trim()}"
    }
}

private fun buildIdeaInputSchema(spec: ToolSpec): CodeBlock {
    val patternFields = inputFieldsForPattern(spec)
    val builder = CodeBlock.builder()
    builder.add("%T.ofPropertiesSchema(\n", MCP_TOOL_SCHEMA)
    builder.add("properties = %M {\n", BUILD_JSON_OBJECT)
    builder.add("  put(%S, %M {\n", "path", BUILD_JSON_OBJECT)
    builder.add("    put(%S, %T(%S))\n", "type", JSON_PRIMITIVE, "string")
    builder.add("    put(%S, %T(%S))\n", "description", JSON_PRIMITIVE, PATH_DESCRIPTION)
    builder.add("  })\n")
    patternFields.forEach { field ->
        builder.add("  put(%S, ", field.schemaKey)
        builder.add(fieldSchemaObject(field, schemaIndent = "    ", closingIndent = "  "))
        builder.add(")\n")
    }
    builder.add("  put(%S, %M {\n", PROJECT_PATH_FIELD, BUILD_JSON_OBJECT)
    builder.add("    put(%S, %T(%S))\n", "type", JSON_PRIMITIVE, "string")
    builder.add("    put(%S, %T(%S))\n", "description", JSON_PRIMITIVE, PROJECT_PATH_DESCRIPTION)
    builder.add("  })\n")
    builder.add("},\n")
    builder.add("requiredProperties = setOf(%S", "path")
    patternFields
        .filter { !it.nullable && it.default == null }
        .forEach { field -> builder.add(", %S", field.schemaKey) }
    builder.add("),\n")
    builder.add("definitions = emptyMap<String, %T>(),\n", JSON_ELEMENT)
    builder.add(")")
    return builder.build()
}

private fun inputFieldsForPattern(spec: ToolSpec): List<FieldSpec> {
    return when (val pattern = spec.inputPattern) {
        ToolInputPattern.WasmOnly -> emptyList()
        ToolInputPattern.WasmPathLabel -> emptyList()
        ToolInputPattern.WasmWithBaseline -> listOf(inputField(spec.input, "baselinePath"))
        ToolInputPattern.WasmWithBinding -> listOf(inputField(spec.input, "bindingPath"))
        ToolInputPattern.WasmWithConfig -> listOf(inputField(spec.input, "configPath"))
        ToolInputPattern.FunctionPage -> listOf(inputField(spec.input, "offset"), inputField(spec.input, "limit"))
        ToolInputPattern.Funcidx -> listOf(inputField(spec.input, "funcidx"))
        ToolInputPattern.FunctionNameSearch -> listOf(inputField(spec.input, "query"), inputField(spec.input, "limit"))
        ToolInputPattern.ExportNameSearch -> listOf(inputField(spec.input, "query"), inputField(spec.input, "limit"))
        ToolInputPattern.Indices -> listOf(inputField(spec.input, "indices"))
        is ToolInputPattern.ClosedRange -> listOf(inputField(spec.input, pattern.parameterName))
        ToolInputPattern.DataSegments -> listOf(
            inputField(spec.input, "segmentRange"),
            inputField(spec.input, "includeExports"),
            inputField(spec.input, "includeGlobals"),
            inputField(spec.input, "minByteLength"),
        )
        ToolInputPattern.ArtifactQuery -> listOf(
            inputField(spec.input, "operation"),
            inputField(spec.input, "entityTypes"),
            inputField(spec.input, "query"),
            inputField(spec.input, "baselinePath"),
            inputField(spec.input, "bindingPath"),
            inputField(spec.input, "configPath"),
            inputField(spec.input, "startName"),
            inputField(spec.input, "startFuncidx"),
            inputField(spec.input, "relations"),
            inputField(spec.input, "limit"),
            inputField(spec.input, "detail"),
            inputField(spec.input, "maxBytes"),
        )
        ToolInputPattern.PolicyWithBaselineAndLog -> listOf(
            inputField(spec.input, "baselinePath"),
            inputField(spec.input, "policyPath"),
            inputField(spec.input, "logPath"),
        )
        ToolInputPattern.RuntimeCompatibility -> listOf(
            inputField(spec.input, "runtime"),
            inputField(spec.input, "version"),
        )
    }
}

private fun buildToolSchema(cls: ClassSpec): CodeBlock {
    val builder = CodeBlock.builder()
    builder.add("%T.ofPropertiesSchema(\n", MCP_TOOL_SCHEMA)
    builder.add("properties = %M {\n", BUILD_JSON_OBJECT)
    cls.fields.forEach { field ->
        builder.add("  put(%S, ", field.schemaKey)
        builder.add(fieldSchemaObject(field, schemaIndent = "    ", closingIndent = "  "))
        builder.add(")\n")
    }
    builder.add("},\n")
    builder.add("requiredProperties = setOf(")
    val required = cls.fields.filter { !it.nullable && it.default == null }.map { it.schemaKey }
    required.forEachIndexed { index, key ->
        if (index > 0) builder.add(", ")
        builder.add("%S", key)
    }
    builder.add("),\n")
    builder.add("definitions = emptyMap<String, %T>(),\n", JSON_ELEMENT)
    builder.add(")")
    return builder.build()
}

private fun fieldSchemaObject(field: FieldSpec, schemaIndent: String, closingIndent: String): CodeBlock {
    val b = CodeBlock.builder()
    b.add("%M {\n", BUILD_JSON_OBJECT)
    emitTypeSchema(field, b, indent = schemaIndent)
    field.describe?.let {
        b.add("${schemaIndent}put(%S, %T(%S))\n", "description", JSON_PRIMITIVE, it)
    }
    field.default?.let {
        b.add("${schemaIndent}put(%S, %T(%L))\n", "default", JSON_PRIMITIVE, schemaDefaultValue(field))
    }
    emitFieldConstraints(field, b, indent = schemaIndent)
    b.add("$closingIndent}")
    return b.build()
}

private fun emitTypeSchema(field: FieldSpec, builder: CodeBlock.Builder, indent: String) {
    when (val type = field.type) {
        is FieldType.ListOf -> {
            emitJsonType(builder, indent, "array", nullable = field.nullable)
            builder.add("${indent}put(%S, %M {\n", "items", BUILD_JSON_OBJECT)
            emitTypeSchema(type.element, builder, indent = "$indent  ")
            field.itemMinimum?.let {
                builder.add("$indent  put(%S, %T(%L))\n", "minimum", JSON_PRIMITIVE, it)
            }
            field.itemMaximum?.let {
                builder.add("$indent  put(%S, %T(%L))\n", "maximum", JSON_PRIMITIVE, it)
            }
            builder.add("${indent}})\n")
        }
        is FieldType.MapOf -> {
            emitJsonType(builder, indent, "object", nullable = field.nullable)
            builder.add("${indent}put(%S, %M {\n", "additionalProperties", BUILD_JSON_OBJECT)
            emitTypeSchema(type.value, builder, indent = "$indent  ")
            builder.add("${indent}})\n")
        }
        else -> emitTypeSchema(type, builder, indent, nullable = field.nullable)
    }
}

private fun emitTypeSchema(
    type: FieldType,
    builder: CodeBlock.Builder,
    indent: String,
    nullable: Boolean = false,
) {
    when (type) {
        FieldType.Int32,
        FieldType.Int64,
        FieldType.UInt32,
        FieldType.ByteT -> emitJsonType(builder, indent, "integer", nullable)
        FieldType.Float64 -> emitJsonType(builder, indent, "number", nullable)
        FieldType.BooleanT -> emitJsonType(builder, indent, "boolean", nullable)
        FieldType.StringT,
        FieldType.ByteArrayT -> emitJsonType(builder, indent, "string", nullable)
        is FieldType.ListOf -> {
            emitJsonType(builder, indent, "array", nullable)
            builder.add("${indent}put(%S, %M {\n", "items", BUILD_JSON_OBJECT)
            emitTypeSchema(type.element, builder, indent = "$indent  ")
            builder.add("${indent}})\n")
        }
        is FieldType.MapOf -> {
            emitJsonType(builder, indent, "object", nullable)
            builder.add("${indent}put(%S, %M {\n", "additionalProperties", BUILD_JSON_OBJECT)
            emitTypeSchema(type.value, builder, indent = "$indent  ")
            builder.add("${indent}})\n")
        }
        is FieldType.ClassRef -> {
            emitJsonType(builder, indent, "object", nullable)
            builder.add("${indent}put(%S, %M {\n", "properties", BUILD_JSON_OBJECT)
            type.clazz.fields.forEach { nested ->
                builder.add("$indent  put(%S, ", nested.schemaKey)
                builder.add(fieldSchemaObject(nested, schemaIndent = "$indent    ", closingIndent = "$indent  "))
                builder.add(")\n")
            }
            builder.add("${indent}})\n")
            val requiredFields = type.clazz.fields.filter { !it.nullable && it.default == null }
            if (requiredFields.isNotEmpty()) {
                builder.add("${indent}put(%S, %M {\n", "required", BUILD_JSON_ARRAY)
                requiredFields.forEach { req ->
                    builder.add("$indent  add(%T(%S))\n", JSON_PRIMITIVE, req.schemaKey)
                }
                builder.add("${indent}})\n")
            }
        }
    }
}

private fun emitJsonType(
    builder: CodeBlock.Builder,
    indent: String,
    jsonType: String,
    nullable: Boolean,
) {
    if (!nullable) {
        builder.add("${indent}put(%S, %T(%S))\n", "type", JSON_PRIMITIVE, jsonType)
        return
    }

    builder.add("${indent}put(%S, %M {\n", "type", BUILD_JSON_ARRAY)
    builder.add("$indent  add(%T(%S))\n", JSON_PRIMITIVE, jsonType)
    builder.add("$indent  add(%T(%S))\n", JSON_PRIMITIVE, "null")
    builder.add("${indent}})\n")
}

private fun emitFieldConstraints(field: FieldSpec, builder: CodeBlock.Builder, indent: String) {
    field.minimum?.let {
        builder.add("${indent}put(%S, %T(%L))\n", "minimum", JSON_PRIMITIVE, it)
    }
    field.maximum?.let {
        builder.add("${indent}put(%S, %T(%L))\n", "maximum", JSON_PRIMITIVE, it)
    }
    field.maxItems?.let {
        builder.add("${indent}put(%S, %T(%L))\n", "maxItems", JSON_PRIMITIVE, schemaIntValue(it))
    }
    field.maxLength?.let {
        builder.add("${indent}put(%S, %T(%L))\n", "maxLength", JSON_PRIMITIVE, schemaIntValue(it))
    }
}

private fun schemaIntValue(value: SchemaIntValue): CodeBlock {
    return when (value) {
        is SchemaIntValue.Literal -> CodeBlock.of("%L", value.value)
        SchemaIntValue.MaxInlineWasmBytes -> CodeBlock.of("%T.MAX_INLINE_WASM_BYTES", HEXANA_ANALYSIS_LIMITS)
        SchemaIntValue.MaxInlineWasmBase64Length ->
            CodeBlock.of("((%T.MAX_INLINE_WASM_BYTES + 2) / 3) * 4", HEXANA_ANALYSIS_LIMITS)
    }
}

private fun schemaDefaultValue(field: FieldSpec): CodeBlock {
    return when (val value = field.default) {
        is Int,
        is Long,
        is Double,
        is Boolean -> CodeBlock.of("%L", value)
        is String -> CodeBlock.of("%S", value)
        else -> error("Field '${field.name}' has unsupported schema default value `${field.default}`.")
    }
}

