        ToolInputPattern.ArtifactQuery -> listOf(
            inputField(spec.input, "operation"),
            inputField(spec.input, "entityTypes"),
            inputField(spec.input, "query"),
            inputField(spec.input, "baselinePath"),
            inputField(spec.input, "bindingPath"),
